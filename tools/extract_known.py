#!/usr/bin/env python3
"""Build public/data/known-addresses.js from the label list embedded in public/orion.html.

The three original pages each carry their own copy of ~930 labelled addresses (exchanges, hacks, ...).
The workspace loads one shared copy instead. Duplicates are merged: the first label wins, and a different
label for the same address is kept as `alt` so the workspace can show "also listed as ...".

Usage:  python tools/extract_known.py            (re-run whenever the list in orion.html changes)
"""
import json, pathlib, re, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "public" / "orion.html"
DST = ROOT / "public" / "data" / "known-addresses.js"

ENTRY = re.compile(r'\{\s*"address"\s*:\s*"([^"]+)"\s*,\s*"label"\s*:\s*"([^"]*)"\s*\}')
ADDRESS = re.compile(r"^(bc1[a-z0-9]{11,87}|[13][a-km-zA-HJ-NP-Z1-9]{25,34})$")


def main():
    text = SRC.read_text(encoding="utf-8")
    start = text.index("knownAddresses = [")
    end = text.index("knownCheck = [", start)
    entries = ENTRY.findall(text[start:end])
    raw_rows = text[start:end].count('"address"')
    if len(entries) != raw_rows:
        sys.exit(f"parsed {len(entries)} entries but the block has {raw_rows} rows: the list format changed, fix ENTRY")

    known, order, bad = {}, [], []
    for addr, label in entries:
        label = label.strip()
        if not ADDRESS.match(addr):
            bad.append(addr)
        if addr not in known:
            known[addr] = {"label": label}
            order.append(addr)
        elif known[addr]["label"] != label and label not in known[addr].get("alt", []):
            known[addr].setdefault("alt", []).append(label)

    conflicts = [(a, known[a]["label"], known[a]["alt"]) for a in order if "alt" in known[a]]
    DST.parent.mkdir(parents=True, exist_ok=True)
    body = ",\n".join(f"  {json.dumps(a)}: {json.dumps(known[a], ensure_ascii=False)}" for a in order)
    DST.write_text(
        "/* Generated by tools/extract_known.py from the list in public/orion.html. Do not edit by hand. */\n"
        "window.ORION_KNOWN = {\n" + body + "\n};\n", encoding="utf-8")

    print(f"{len(entries)} rows -> {len(order)} distinct addresses -> {DST.relative_to(ROOT)}")
    print(f"{len(entries) - len(order)} duplicate rows merged, {len(conflicts)} addresses with conflicting labels")
    for a, first, alt in conflicts:
        print(f"  {a}: kept {first!r}, also {alt}")
    if bad:
        print(f"WARNING: {len(bad)} entries do not look like Bitcoin addresses: {bad[:5]}")


if __name__ == "__main__":
    main()
